"""warden: install the daemon and generate its drop-in from the profile.

This role runs last, so it can read what every other role contributed to the
context — the WAF log(s) and their mode, the worker accounts, the FIM sites,
the health checks, the trusted networks — and turn them into one Warden
drop-in (``/etc/warden/conf.d/60-warden-lab.toml``). It also ships a benign
synthetic webshell signature so the FIM/quarantine tests never need real
malware, and installs Warden from a release, a local ``.deb`` or a source
tree per ``[warden] source``.

The drop-in's allowlist always contains the lab's trusted client(s), so a
block in a test — or in production — can never lock the operator out.
"""

from __future__ import annotations

import os
import platform
import tempfile

from .. import net as netmod
from .. import roles
from ..render import FileSpec, Plan, render_template
from ..util import defer_service_starts, die, have, run, sha256_file, step, warn

WARDEN_ETC = "/etc/warden"
DROPIN = f"{WARDEN_ETC}/conf.d/60-warden-lab.toml"
SIGS = f"{WARDEN_ETC}/signatures.d/lab.toml"
WEBSHELL_MARKER = "WARDEN_LAB_WEBSHELL_MARKER"


def _active(p) -> bool:
    return True


def packages(p) -> list[str]:
    """Provision utilities needed by the selected Warden install source."""
    if p.warden.source == "release":
        # curl/CA roots must exist before the role's post-apply release fetch.
        return ["curl", "ca-certificates"]
    if p.warden.source == "source":
        return ["git", "build-essential", "pkg-config", "libsystemd-dev", "libdbus-1-dev"]
    return []


# --------------------------------------------------------------------------
# TOML emission (tomllib reads but cannot write)
# --------------------------------------------------------------------------


def _tstr(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _tarr(items) -> str:
    return "[" + ", ".join(_tstr(i) for i in items) + "]"


def render(p, ctx) -> Plan:
    plan = Plan()
    ep = ctx.get("endpoints") or netmod.resolve(p)
    web_users = sorted(set(ctx.get("web_users", [])))
    waf_logs = ctx.get("waf_logs", [])
    fim_sites = ctx.get("fim_sites", [])
    health = ctx.get("health_checks", [])
    err_log = ctx.get("waf_error_log", "/var/log/warden-lab/nginx/portal.error.log")

    allow = list(dict.fromkeys(ep.trusted + [ep.cli_v4, ep.cli_v6]))
    lines: list[str] = []
    lines.append("# Warden drop-in generated by the Warden Lab Kit — do not hand-edit.")
    lines.append(f"# profile: {p.name}   front: {p.front}   waf: {p.waf.engine}/{p.waf.mode}")
    lines.append("")
    # Always write this explicitly. An older operator override or pre-existing
    # main config must not accidentally enable remediation on a first Kit apply.
    lines += ["[daemon]", f"dry_run = {'false' if p.warden.enforce else 'true'}", ""]
    lines += ["[events]", "max_info_per_minute = 600", ""]

    # firewall: allowlist + IPv6 aggregation
    lines += ["[actions.firewall]"]
    lines.append(f"allowlist = {_tarr(allow)}")
    lines.append("ipv6_prefix = 64")
    lines.append("protect_ssh_sessions = true")
    lines.append("")

    # the worker accounts, so web_spawn and log trust apply to them
    lines += ["[process]"]
    lines.append(f"web_users = {_tarr(web_users)}")
    lines.append("")

    # WAF logs for the selected mode
    lines += ["[waf]", "enabled = true", "discover = false", ""]
    for wl in waf_logs:
        path = wl["path"].replace("@ERRORLOG@", err_log)
        lines.append("[[waf.log]]")
        lines.append(f"path = {_tstr(path)}")
        lines.append(f"format = {_tstr(wl.get('format', 'auto'))}")
        if wl.get("site"):
            lines.append(f"site = {_tstr(wl['site'])}")
        if wl.get("storage_dir"):
            lines.append(f"storage_dir = {_tstr(wl['storage_dir'])}")
        lines.append("")

    # FIM sites
    for s in fim_sites:
        lines.append("[[fim.site]]")
        lines.append(f"name = {_tstr(s['name'])}")
        lines.append(f"root = {_tstr(s['root'])}")
        if s.get("access_log"):
            lines.append(f"access_log = {_tstr(s['access_log'])}")
        if s.get("no_scripts"):
            lines.append(f"no_scripts = {_tarr(s['no_scripts'])}")
        if s.get("restart_unit"):
            lines.append(f"restart_unit = {_tstr(s['restart_unit'])}")
        lines.append("")

    # health checks
    for h in health:
        lines.append("[[health.check]]")
        lines.append(f"name = {_tstr(h['name'])}")
        lines.append(f"type = {_tstr(h['type'])}")
        if h["type"] == "http":
            lines.append(f"url = {_tstr(h['url'])}")
        elif h["type"] == "tcp":
            lines.append(f"address = {_tstr(h['address'])}")
        elif h["type"] == "command":
            lines.append(f"program = {_tstr(h['program'])}")
            if h.get("args"):
                lines.append(f"args = {_tarr(h['args'])}")
            if h.get("expect_output"):
                lines.append(f"expect_output = {_tstr(h['expect_output'])}")
        if h.get("unit"):
            lines.append(f"unit = {_tstr(h['unit'])}")
        lines.append("")

    content = "\n".join(lines).rstrip() + "\n"
    plan.files.append(
        FileSpec(DROPIN, content, "root", "root", 0o640, "warden",
                 validate=("wardend",), restart=())
    )
    # the synthetic webshell signature (benign; drives the FIM/quarantine tests)
    plan.files.append(
        FileSpec(SIGS, render_template("warden/lab-signatures.toml", {"MARKER": WEBSHELL_MARKER}),
                 "root", "root", 0o640, "warden")
    )
    ctx.set("warden_dropin", content)
    return plan


def post_apply(p, ctx) -> None:
    src = p.warden.source
    if src != "none":
        os.makedirs(f"{WARDEN_ETC}/conf.d", exist_ok=True)
        os.makedirs(f"{WARDEN_ETC}/signatures.d", exist_ok=True)
    if src in {"release", "deb", "source"}:
        # Debian postinst scripts may start/enable a daemon before we can
        # validate the merged main+drop-in config. Defer starts until below.
        with defer_service_starts():
            if src == "release":
                _install_release(p)
            elif src == "deb":
                _install_deb(p.warden.deb_file, p.warden.deb_sha256)
            else:
                _install_source(p)
    elif src == "none" and not have("wardend"):
        warn("warden.source = none and wardend is not installed; the drop-in was written but not validated")

    # The Debian package intentionally does not enable/start the service. Do so
    # only after validating both the main config and the kit-generated drop-in.
    if have("wardend"):
        main = f"{WARDEN_ETC}/warden.toml"
        check = run(["wardend", "--check-config", "--config", main], check=False)
        if not check.ok:
            die(f"the generated Warden configuration does not validate:\n{check.err or check.out}")
        if have("systemctl") and src != "none":
            run(["systemctl", "daemon-reload"])
            run(["systemctl", "enable", "wardend.service"])
            active = run(["systemctl", "is-active", "--quiet", "wardend.service"], check=False, quiet=True)
            if active.ok:
                run(["systemctl", "restart", "wardend.service"])
            else:
                run(["systemctl", "start", "wardend.service"])
            state = run(["systemctl", "is-active", "wardend.service"], check=False, quiet=True)
            if not state.ok or state.out.strip() != "active":
                logs = run(["journalctl", "-u", "wardend.service", "-n", "40", "--no-pager"], check=False, quiet=True)
                die("wardend.service did not become active after installation:\n" + (logs.out or logs.err))
            step("wardend.service enabled and active")


def release_url(version: str) -> str:
    """Return the immutable release asset URL for the pinned Debian package."""
    return f"https://github.com/commeta/warden/releases/download/{version}/warden_{version}-1_amd64.deb"


def _install_release(p) -> None:
    # The release assets use the plain tag (0.14.3), not a v-prefixed tag.
    # Only amd64 has a published .deb in this pinned release.
    arch_result = run(["dpkg", "--print-architecture"], check=False, quiet=True)
    arch = arch_result.out.strip()
    if arch != "amd64":
        die(
            f"Warden release {p.warden.version} currently provides a Debian package for amd64, not {arch or platform.machine()}. "
            "Use warden.source='source' with a Rust 1.88+ toolchain on this architecture."
        )
    if have("wardend") and _version() == p.warden.version:
        step(f"wardend {p.warden.version} already installed")
        return
    url = release_url(p.warden.version)
    if not have("curl"):
        die("curl is required to download a Warden release; it should have been installed from the profile dependencies")
    fd, tmp = tempfile.mkstemp(prefix="warden-lab-release-", suffix=".deb", dir="/var/tmp")
    os.close(fd)
    try:
        os.chmod(tmp, 0o600)
        step(f"download pinned Warden release {p.warden.version}")
        r = run(
            ["curl", "--fail", "--location", "--silent", "--show-error", "--retry", "3",
             "--connect-timeout", "15", "--max-time", "180", "--proto", "=https",
             "--proto-redir", "=https", "--tlsv1.2", "--output", tmp, url],
            check=False,
        )
        if not r.ok:
            detail = r.err.strip() or r.out.strip() or "curl failed"
            die(
                f"could not download {url}: {detail}. Verify DNS/HTTPS access to GitHub and the pinned release asset; "
                "no unverified package was installed."
            )
        _install_deb(tmp, p.warden.sha256)
    finally:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass


def _install_deb(path: str, sha: str) -> None:
    if not path or not os.path.isfile(path):
        die(f"Warden .deb not found: {path}")
    if not sha or len(sha) != 64 or any(c not in "0123456789abcdefABCDEF" for c in sha):
        die("a pinned 64-character warden.sha256/deb_sha256 is required; refusing to install an unverified package")
    got = sha256_file(path)
    if got.lower() != sha.lower():
        die(f"{path}: sha256 {got} != pinned {sha}; refusing to install")
    run(["apt-get", "install", "-y", "--no-install-recommends", path], env={"DEBIAN_FRONTEND": "noninteractive"})


def _install_source(p) -> None:
    src = p.warden.source_dir
    if not src or not os.path.isdir(src):
        die(f"warden.source=source needs source_dir (a Warden tree): {src!r}")
    builder = os.path.join(src, "scripts", "build-deb.sh")
    if os.path.exists(builder):
        run(["bash", builder, "--portable"], cwd=src)
        import glob
        debs = sorted(glob.glob(os.path.join(src, "target", "**", "warden_*_amd64.deb"), recursive=True))
        if debs:
            # Locally-built package: pin the exact bytes generated in this run
            # before passing the package to APT.
            _install_deb(debs[-1], sha256_file(debs[-1]))
            return
    installer = os.path.join(src, "scripts", "install.sh")
    if os.path.exists(installer):
        run(["bash", installer], cwd=src)
        return
    die("no build-deb.sh or install.sh in the source tree")


def _version() -> str:
    r = run(["wardend", "--version"], check=False, quiet=True)
    parts = (r.out or r.err).split()
    return parts[-1] if parts else ""


def verify(p, ctx):
    out = [("drop-in present", os.path.exists(DROPIN), DROPIN)]
    if p.warden.source != "none":
        out.append(("wardend installed", have("wardend"), ""))
    if have("wardend"):
        r = run(["wardend", "--check-config", "--config", f"{WARDEN_ETC}/warden.toml"], check=False, quiet=True)
        out.append(("wardend --check-config", r.ok, (r.err or r.out).strip()[:160]))
        if p.warden.source != "none" and have("systemctl"):
            active = run(["systemctl", "is-active", "wardend.service"], check=False, quiet=True)
            out.append(("wardend.service active", active.ok and active.out.strip() == "active", active.out.strip()))
    return out


ROLE = roles.Role(name="warden", packages=packages, render=render, post_apply=post_apply, verify=verify, active=_active)
