"""Migrate a 1.x ``lab.env`` to a 2.0 ``lab.toml``.

The old kit had five keys and a loopback-only, Apache + ModSecurity 2.9
layout. This reads ``lab.env`` with the same strict rules the 1.x parser used
(KEY=value, no quotes, no execution) and writes the equivalent profile, so an
operator upgrading does not start from a blank file.
"""

from __future__ import annotations

import os
import re

from .util import die, warn

_LINE = re.compile(r"^([A-Z][A-Z0-9_]*)=([A-Za-z0-9_./:-]+)$")
_ALLOWED = {"LAB_IP", "ATTACKER_IP", "DB_NAME", "DB_USER", "DB_PASSWORD",
            "WARDEN_VERSION", "WARDEN_DEB_SHA256"}


def _read_env(path: str) -> dict[str, str]:
    if not os.path.exists(path):
        die(f"no {path} to migrate")
    st = os.stat(path)
    if st.st_mode & 0o077:
        warn(f"{path} is group/other-readable; the new lab.toml carries no secrets, but fix the old file's mode")
    out: dict[str, str] = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.lstrip().startswith("#"):
                continue
            m = _LINE.match(line)
            if not m:
                die(f"{path}:{n}: expected KEY=value without quotes/spaces")
            key, val = m.group(1), m.group(2)
            if key not in _ALLOWED:
                die(f"{path}:{n}: unsupported key {key!r}")
            out[key] = val
    return out


def migrate(env_path: str, out_path: str) -> str:
    env = _read_env(env_path)
    version = env.get("WARDEN_VERSION", "")
    sha = env.get("WARDEN_DEB_SHA256", "")
    pinned = sha and not re.fullmatch(r"0{64}", sha)
    toml = f"""# Generated by 'labctl migrate' from {os.path.basename(env_path)}.
# The 1.x kit was Apache + ModSecurity 2.9 on loopback; this is the equivalent
# 2.0 profile. Review it, then run 'sudo ./labctl plan'.
[lab]
name = "migrated"
front = "apache-prefork"     # 1.x front (Apache prefork + mod_php + mod_security2)
hostname = "lab.local"
sites = ["portal", "wordpress"]
services = []                 # 1.x had no microservices
databases = ["mariadb"]

[net]
mode = "loopback"             # 1.x was loopback-only (attacker was {env.get('ATTACKER_IP', '127.0.0.2')})
                              # switch to "netns" to exercise real blocks and IPv6, or
                              # "external" with external_iface + trusted for production.

[waf]
engine = "modsec2"
mode = "serial-native"        # the single mode 1.x used
paranoia = 1

[crs]
source = "package"            # CRS 3.3.5 from the Ubuntu archive

[warden]
source = {'"release"' if pinned else '"none"'}
version = "{version}"
sha256 = "{sha}"
enforce = false
"""
    if os.path.exists(out_path):
        die(f"{out_path} already exists; remove it or choose --out")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(toml)
    if not pinned:
        warn("the old SHA was unpinned; warden.source is 'none'. Pin warden.version+sha256 to install.")
    return out_path
